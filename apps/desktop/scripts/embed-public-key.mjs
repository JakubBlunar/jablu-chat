#!/usr/bin/env node
// Build prehook: write apps/desktop/src/main/updateSigningKey.generated.ts
// from the UPDATE_PUBLIC_KEY_PEM env var. If missing, write a stub that
// disables auto-update at runtime so we can't accidentally ship an
// unsigned-update build.

import { writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const outPath = resolve(here, '..', 'src', 'main', 'updateSigningKey.generated.ts')

const pem = process.env.UPDATE_PUBLIC_KEY_PEM?.trim()

const header = '// AUTO-GENERATED by scripts/embed-public-key.mjs — do not edit.\n// Regenerate by running the build with UPDATE_PUBLIC_KEY_PEM set.\n'

if (!pem) {
  const stub = `${header}
export const UPDATE_PUBLIC_KEY_PEM: string | null = null
export const UPDATE_SIGNING_DISABLED_REASON: string | null =
  'UPDATE_PUBLIC_KEY_PEM was not set at build time; auto-update is disabled.'
`
  writeFileSync(outPath, stub)
  console.warn('[embed-public-key] UPDATE_PUBLIC_KEY_PEM not set — auto-update will be DISABLED in this build.')
  process.exit(0)
}

if (!pem.includes('BEGIN PUBLIC KEY') || !pem.includes('END PUBLIC KEY')) {
  console.error('[embed-public-key] UPDATE_PUBLIC_KEY_PEM does not look like a PEM public key.')
  process.exit(1)
}

const escaped = pem.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$/g, '\\$')

const contents = `${header}
export const UPDATE_PUBLIC_KEY_PEM: string | null = \`${escaped}\n\`
export const UPDATE_SIGNING_DISABLED_REASON: string | null = null
`

writeFileSync(outPath, contents)
console.log(`[embed-public-key] Wrote ${outPath}`)
